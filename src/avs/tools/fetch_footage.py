"""Download the public starter footage, trim it, and write the attribution and licence file.

    python -m avs.tools.fetch_footage [--only CLIP_ID ...]

Sources are listed in footage/starter.json. Each source file is downloaded once into
data/footage/raw (resumable, size-checked), then trimmed and re-encoded to a silent
H.264 MP4 in data/footage/clips. A source that cannot be fetched is skipped and recorded
as a gap in data/footage/ATTRIBUTION.md, so the rest of the set is still usable.
"""

from __future__ import annotations

import argparse
import json
import re
import ssl
import sys
from datetime import UTC, datetime
from pathlib import Path
from urllib.parse import urlparse

import httpx
import truststore

from avs.media import encode_h264, probe
from avs.settings import REPO_ROOT, get_settings

MANIFEST = REPO_ROOT / "footage" / "starter.json"
ALLOWED_LICENCES = ("CC BY 4.0", "Creative Commons BY-SA", "Pexels License")
USER_AGENT = "avs-poc-footage-fetch/0.1"
# The macOS trust store, so downloads work behind a TLS-inspecting company proxy just as curl does.
TLS = truststore.SSLContext(ssl.PROTOCOL_TLS_CLIENT)


def load_manifest(path: Path = MANIFEST) -> dict:
    manifest = json.loads(path.read_text())
    for clip in manifest["clips"]:
        licence = manifest["sources"][clip["source"]]["licence"]
        if not licence.startswith(ALLOWED_LICENCES) or re.search(r"\bNC\b", licence):
            raise ValueError(f"{clip['id']}: licence {licence!r} is not allowed")
    return manifest


def footage_dir() -> Path:
    return get_settings().data_dir / "footage"


def clip_path(clip_id: str) -> Path:
    return footage_dir() / "clips" / f"{clip_id}.mp4"


def download(url: str, dest: Path, expected_bytes: int | None) -> None:
    """Resumable download; a complete file of the expected size is left alone."""
    dest.parent.mkdir(parents=True, exist_ok=True)
    if dest.exists() and expected_bytes and dest.stat().st_size == expected_bytes:
        return
    partial = dest.with_name(dest.name + ".part")
    offset = partial.stat().st_size if partial.exists() else 0
    headers = {"User-Agent": USER_AGENT}
    if offset:
        headers["Range"] = f"bytes={offset}-"
    timeout = httpx.Timeout(30.0, read=120.0)
    with httpx.stream("GET", url, headers=headers, follow_redirects=True, timeout=timeout, verify=TLS) as r:
        if r.status_code == 200 and offset:
            offset = 0  # the server ignored the range request; start again
        elif r.status_code not in (200, 206):
            raise RuntimeError(f"HTTP {r.status_code} for {url}")
        with partial.open("ab" if offset else "wb") as out:
            for chunk in r.iter_bytes(1024 * 1024):
                out.write(chunk)
    size = partial.stat().st_size
    if expected_bytes and size != expected_bytes:
        raise RuntimeError(f"downloaded {size} bytes, expected {expected_bytes}")
    partial.replace(dest)


def fetch_clip(clip: dict) -> dict:
    raw = footage_dir() / "raw" / Path(urlparse(clip["url"]).path).name
    if clip["source"] == "nvidia":
        # Every NVIDIA camera file is called video.mp4; keep the camera in the cache name.
        raw = raw.with_name(f"{clip['id']}-{raw.name}")
    download(clip["url"], raw, clip.get("bytes"))
    out = clip_path(clip["id"])
    if not out.exists():
        encode_h264(raw, out, start=clip["trim_start"] or None, duration=clip["trim_duration"])
    info = probe(out)
    return {"id": clip["id"], "path": str(out), "duration": round(info.duration, 2), "width": info.width, "height": info.height}


def write_attribution(manifest: dict, fetched: dict[str, dict], gaps: dict[str, str]) -> Path:
    lines = [
        "# Starter footage: attribution and licences",
        "",
        f"Generated by `scripts/fetch_footage.sh` from `footage/starter.json` on {datetime.now(UTC):%Y-%m-%d %H:%M UTC}.",
        "Every clip below was trimmed and re-encoded to silent H.264; nothing else about the picture was changed.",
        "",
        "## Sources",
        "",
    ]
    used = {c["source"] for c in manifest["clips"]}
    for key, source in manifest["sources"].items():
        if key not in used:
            continue
        lines += [
            f"### {source['name']}",
            "",
            f"- Licence: {source['licence']} ({source['licence_url']})",
            f"- Attribution: {source['attribution']}",
            f"- Home: {source['home']}",
            "",
        ]
    lines += ["## Clips", "", "| Clip | Camera | Place | Start (local) | Trim | Use | Source file |", "|---|---|---|---|---|---|---|"]
    for clip in manifest["clips"]:
        trim = f"{clip['trim_start']}s + {clip['trim_duration']}s" if clip["trim_duration"] else f"from {clip['trim_start']}s, whole file"
        status = "" if clip["id"] in fetched else " (not fetched)"
        url = clip.get("page") or clip["url"]
        lines.append(
            f"| {clip['id']}{status} | {clip['camera_id']} | {clip['place']} | {clip['start_time']} | {trim} | {clip['use']} | {url} |"
        )
    lines += ["", "## Gaps", ""]
    if gaps:
        lines += [f"- {clip_id}: could not be fetched ({reason})." for clip_id, reason in gaps.items()]
    else:
        lines.append("- Every clip in the manifest was fetched.")
    lines += [
        "- No usable public CCTV footage shows children, Arabic dress or a Middle-East setting; the lost-child story uses an adult stand-in.",
        "- CAVIAR, NVIDIA and Pexels clips carry no recording time, so their dates and times are illustrative.",
        "",
        "## Left out on purpose",
        "",
    ]
    lines += [f"- {item['source']}: {item['reason']}" for item in manifest["left_out"]]
    path = footage_dir() / "ATTRIBUTION.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    return path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--only", nargs="*", help="fetch only these clip ids")
    args = parser.parse_args(argv)
    manifest = load_manifest()
    fetched: dict[str, dict] = {}
    gaps: dict[str, str] = {}
    for clip in manifest["clips"]:
        if args.only and clip["id"] not in args.only:
            if clip_path(clip["id"]).exists():
                fetched[clip["id"]] = {"id": clip["id"]}
            continue
        try:
            fetched[clip["id"]] = fetch_clip(clip)
            info = fetched[clip["id"]]
            print(f"  ok   {clip['id']:28} {info['duration']:7.1f}s {info['width']}x{info['height']}")
        except Exception as exc:
            gaps[clip["id"]] = str(exc)
            print(f"  GAP  {clip['id']:28} {exc}", file=sys.stderr)
    path = write_attribution(manifest, fetched, gaps)
    print(f"{len(fetched)} clip(s) ready in {footage_dir() / 'clips'}; attribution in {path}")
    return 0 if fetched else 1


if __name__ == "__main__":
    sys.exit(main())
